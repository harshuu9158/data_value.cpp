#include <iostream> // iostream states for input/output library

int main()
{
    // std::cout is used to print the output to the console where cout stands for character output stream and std is the standard namespace
    // << is the insertion operator used to insert the data into the output stream
    std::cout << "Hello, World!" << std::endl;
// std::endl is used to insert a new line character and flush the output buffer
    return 0;
}